#!/usr/bin/env python3
"""Prepare a synthetic recording folder (Mac side, numpy only).

Writes into OUT_DIR:
  SYNTHETIC.json         marker + ground truth (process.sh never lets a folder
                         with this file claim physical accuracy)
  synth_params.json      every scene parameter (input to write_bag.py)
  fastlio_synthetic.yaml FAST-LIO config that travels with the recording:
                         its topics, frames and extrinsic describe THIS
                         synthetic sensor, not the Mid-360

    prepare.py OUT_DIR --end-offset-m DX [DY DZ] [--seed N] [--lidar-topic T]
               [--imu-topic T] [--imu-rate HZ]
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scene import Path, SceneParams, ground_truth, scan_count  # noqa: E402

# Upstream FAST_LIO_ROS2 config/mid360.yaml layout, with this synthetic
# sensor's topics and an exact (identity) lidar-IMU extrinsic.
CONFIG = """/**:
    ros__parameters:
        feature_extract_enable: false
        point_filter_num: 3
        max_iteration: 3
        filter_size_surf: 0.5
        filter_size_map: 0.5
        cube_side_length: 1000.0
        runtime_pos_log_enable: false
        map_file_path: "./test.pcd"

        common:
            lid_topic:  "{lidar}"
            imu_topic:  "{imu}"
            time_sync_en: false
            time_offset_lidar_to_imu: 0.0

        preprocess:
            lidar_type: 1                # Livox CustomMsg
            scan_line:  {lines}
            blind: 0.5
            timestamp_unit: 3
            scan_rate: {scan_rate}

        mapping:
            acc_cov: 0.1
            gyr_cov: 0.1
            b_acc_cov: 0.0001
            b_gyr_cov: 0.0001
            fov_degree:    360.0
            det_range:     100.0
            extrinsic_est_en:  false     # synthetic: lidar and IMU are exactly co-located
            extrinsic_T: [ 0.0, 0.0, 0.0 ]
            extrinsic_R: [ 1., 0., 0.,
                            0., 1., 0.,
                            0., 0., 1.]

        publish:
            path_en: true
            effect_map_en: false
            map_en: true
            scan_publish_en:  true
            dense_publish_en: false
            scan_bodyframe_pub_en: true

        pcd_save:
            pcd_save_en: true
            interval: -1
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--end-offset-m", type=float, nargs="+", required=True,
                    help="true end position minus start, start frame (x = initial heading)")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--lidar-topic", default="/synth/lidar_points")
    ap.add_argument("--imu-topic", default="/synth/imu_data")
    ap.add_argument("--lidar-frame", default="synth_lidar")
    ap.add_argument("--imu-frame", default="synth_imu")
    ap.add_argument("--imu-rate", type=float, default=250.0)
    ap.add_argument("--lidar-rate", type=float, default=10.0)
    ap.add_argument("--scan-lines", type=int, default=4)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=JSON",
                    help="override any SceneParams field, e.g. --set points_per_scan=20000")
    args = ap.parse_args(argv)

    off = list(args.end_offset_m) + [0.0] * (3 - len(args.end_offset_m))
    extra = {}
    for item in args.set:
        key, _, value = item.partition("=")
        if key not in SceneParams.__dataclass_fields__ or key in ("end_offset_m", "seed"):
            ap.error(f"--set {key}: not a settable SceneParams field")
        v = json.loads(value)
        extra[key] = tuple(v) if isinstance(v, list) and key != "boxes" else v
    p = SceneParams(end_offset_m=tuple(off[:3]), seed=args.seed,
                    imu_rate_hz=args.imu_rate, lidar_rate_hz=args.lidar_rate, **extra)
    path = Path(p)
    os.makedirs(args.out, exist_ok=False)
    with open(os.path.join(args.out, "synth_params.json"), "w") as f:
        json.dump(p.as_json(), f, indent=2)
    truth = ground_truth(path)
    marker = {
        "schema": "spatio.synthetic_recording/1",
        "synthetic": True,
        "statement": "Synthetic recording generated by spatio/walkday/synth. Not a physical walk; "
                     "physical accuracy can never be evaluated from it.",
        "ground_truth": truth,
        "topics": {"lidar": args.lidar_topic, "imu": args.imu_topic},
        "frames": {"lidar": args.lidar_frame, "imu": args.imu_frame},
        "rates_hz": {"lidar": p.lidar_rate_hz, "imu": p.imu_rate_hz},
        "scans": scan_count(path),
        "imu_units": {"linear_acceleration": "g", "angular_velocity": "rad/s"},
    }
    with open(os.path.join(args.out, "SYNTHETIC.json"), "w") as f:
        json.dump(marker, f, indent=2)
    with open(os.path.join(args.out, "fastlio_synthetic.yaml"), "w") as f:
        f.write(CONFIG.format(lidar=args.lidar_topic, imu=args.imu_topic,
                              lines=args.scan_lines, scan_rate=int(round(p.lidar_rate_hz))))
    print(json.dumps({"out": args.out, "true_return_error_3d_m": truth["true_return_error_3d_m"],
                      "duration_s": truth["duration_s"]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
